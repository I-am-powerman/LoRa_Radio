import machine
import neopixel
import time

# Настраиваем светодиод:
# Пин GPIO21, один светодиод (количество = 1)
# Яркость можно регулировать, меняя числа в кортежах (r, g, b) от 0 до 255
pin = machine.Pin(21, machine.Pin.OUT)
np = neopixel.NeoPixel(pin, 1)

# Небольшая пауза, чтобы плата успела "проснуться" после загрузки
time.sleep(0.5)

# Бесконечный цикл, чтобы эффект повторялся постоянно
while True:
    # --- Разные цвета (меняются каждые 0.3 секунды) ---
    
    # Красный (максимум красного, остальные выключены)
    np[0] = (50, 0, 0)  # Уменьшил яркость красного до 50, чтобы не слепил
    np.write()
    time.sleep(0.3)

    # Зеленый
    np[0] = (0, 50, 0)
    np.write()
    time.sleep(0.3)

    # Синий
    np[0] = (0, 0, 50)
    np.write()
    time.sleep(0.3)

    # Желтый (красный + зеленый)
    np[0] = (50, 40, 0)
    np.write()
    time.sleep(0.3)

    # Голубой (зеленый + синий)
    np[0] = (0, 40, 50)
    np.write()
    time.sleep(0.3)

    # Пурпурный (красный + синий)
    np[0] = (50, 0, 40)
    np.write()
    time.sleep(0.3)

    # --- Белый цвет (все три цвета максимально) ---
    # Сделаем его помягче и подольше, как вы просили
    for i in range(5):  # Повторим мерцание белого 5 раз для красоты
        np[0] = (30, 30, 30)  # Мягкий белый
        np.write()
        time.sleep(0.2)
        np[0] = (0, 0, 0)  # Выключаем
        np.write()
        time.sleep(0.1)
    
    # В итоге оставляем гореть белым на 2 секунды
    np[0] = (30, 30, 30)
    np.write()
    time.sleep(2)

    # Можно добавить небольшую паузу перед повтором всего цикла
    # или он начнется сначала сам, так как цикл бесконечный.